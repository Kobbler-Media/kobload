#!/usr/bin/env bash
set -euo pipefail

root_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
env_file="${root_dir}/.env"
override_file="${root_dir}/docker-compose.override.yml"

ensure_env_key() {
    local key="$1" value="$2"
    if ! grep -q "^${key}=" "$env_file" || [[ -z "$(grep "^${key}=" "$env_file" | cut -d= -f2-)" ]]; then
        echo "${key}=${value}" >> "$env_file"
        echo "  Added ${key}"
    else
        echo "  ${key} is set"
    fi
}

echo "=== Kobload Production Setup ==="
echo ""

# --- .env ---
if [[ -f "$env_file" ]]; then
    echo "Found existing .env"
    ensure_env_key "NATS_TOKEN" "$(openssl rand -hex 32)"
else
    echo "Creating .env with defaults..."
    nats_token="$(openssl rand -hex 32)"
    cat > "$env_file" <<EOF
# Kobload production environment
# Generated by setup-prod.sh

NATS_TOKEN=${nats_token}

# Uncomment/edit as needed:
# KOBLOAD_PORT=7080
# KOBLOAD_WEB_PORT=5174
# KOBLOAD_API_KEY=
# KOBLOAD_PUBLIC_URL=http://localhost:7080
# ADMIN_EMAIL=admin@localhost
# ADMIN_PASSWORD=
# PROWLARR_BASE_URL=
# PROWLARR_API_KEY=
# POSTGRES_PASSWORD=kobload
# RUST_LOG=info,kobload_api=info
EOF
    echo "  Created .env"
fi

echo ""

# --- docker-compose.override.yml for external NATS ---
if [[ -f "$override_file" ]]; then
    echo "docker-compose.override.yml already exists — skipping."
else
    read -rp "NATS URL (leave blank for bundled): " nats_url
    if [[ -n "$nats_url" ]]; then
        cat > "$override_file" <<EOF
# Generated by setup-prod.sh — uses external NATS at ${nats_url}
services:
  nats:
    image: busybox:1.37
    command: ["true"]
    restart: "no"
    volumes: []

  api:
    environment:
      NATS_URL: ${nats_url}
    depends_on:
      db:
        condition: service_started
      nats:
        condition: service_completed_successfully
EOF
        echo "  Created docker-compose.override.yml (external NATS)"
    else
        echo "  Skipped — using bundled NATS"
    fi
fi

echo ""
echo "Setup complete. Run:"
echo "  docker compose up -d --build"
